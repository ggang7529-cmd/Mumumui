// 책 소개(카카오 책 검색의 contents) 표시용 정리.
//
// 카카오가 주는 소개는 약 260자짜리 발췌라 문장 한가운데서 끊긴다("…되는 고대 수메르"
// 처럼 마침표도 없이). 그대로 두면 글이 잘린 게 아니라 화면이 고장난 것처럼 보인다.
// 국립중앙도서관 서지정보에서 전문을 받아오는 길도 재봤지만 20권 중 3권(15%)에만
// 있어서, 대부분의 책은 이 발췌가 최선이다. 그래서 데이터를 바꾸는 대신 표시할 때
// "여기서 끊겼다"는 표시를 붙여 발췌로 읽히게 한다.
//
// 브라우저(js/render.js)와 서버 렌더(functions/book/[id].js)가 같은 함수를 쓴다 —
// 한쪽만 고쳐서 두 화면의 문구가 어긋나는 일을 없애려는 것이다.

// 문장이 제대로 끝났는지 판단하는 문자들. 마침표류와 닫는 따옴표·괄호까지 포함한다.
var SENTENCE_END = /[.!?…。？！”’"')\]】」』]$/;

export function formatContents(raw) {
  var text = String(raw || "").trim();
  if (!text) return "";
  // 이미 문장이 온전히 끝났으면 손대지 않는다. 전문을 받아온 책이 그렇다.
  if (SENTENCE_END.test(text)) return text;
  return text + "…";
}
